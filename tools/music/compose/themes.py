# ═════════════════════════ 曲库索引 ════════════════════════

MELODIES: Dict[str, Melody] = {
    m.id: m for m in (
        MENU, FIELD_DAY,
        NIGHT, DAY_HARP, VILLAGE, VILLAGE_MARIMBA, VILLAGE_NIGHT,
        INTERIOR, HALL, STRATEGIC, BATTLE, BATTLE_STRINGS, BATTLEFIELD,
        CONQUEST,
    )
}


def get(melody_id: str) -> Melody:
    if melody_id not in MELODIES:
        raise KeyError("未知旋律: %s（可选：%s）"
                       % (melody_id, ", ".join(sorted(MELODIES))))
    return MELODIES[melody_id]


