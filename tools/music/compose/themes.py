# -*- coding: utf-8 -*-
"""旋律素材库 —— 每个场景一条**自己的**旋律。

口径（2026-09-29 创始人定）：**不再"一条主题讲遍全曲"**。每首曲子有自己的旋律，
整部配乐的统一性改由下面三样东西负责：

  1. **共用的和声语汇**（卡农进行 / 自然小调骨架 / 田园骨架 / 出征骨架）；
  2. **共用的编制纪律**（钢琴为主角、每曲只用一件独奏木管、打击乐只做点状音）；
  3. **共用的写作纪律**（级进为主、留白 ≥8%、一音域内只点一次最高音、
     句尾停在 3 或 5 音而不落主音）。

**每首曲子都有自己的旋律，不共用素材**：全库 17 首里 14 首是完整旋律、3 首是
一次性手势（凯旋 / 折戟 / 抵达）。统一"听起来像一部作品"这件事**不靠共用旋律**，
也不作为写作目标——每首曲子只对一件事负责：在那个场合里好听、待得住。

每条旋律用**音阶级数**记录，因此可以整体搬到任何调上（`degree()` 只认级数，
不认绝对音高）。每条乐句自带推荐移调 `Phrase.transpose`（半音）：同一个级数在钢琴、
长笛、双簧管上的舒适音区不同，D 大调比 G 大调低 5 个半音——一个全局常量必然
让某些声部跑到乐器音域之外，所以移调跟着**乐句**走，并在 `register` 里写明理由。

字段 = (小节, 小节内起始拍, 时值拍, 音阶级数, 八度偏移, 力度)，约定同
`common.render_theme`。力度是"乐句内部的相对强弱"，它同时是**采样层的选择器**
（见 common.VELOCITY_TRIM），所以基准值都取在 52~70 这一段。
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Tuple

Event = Tuple[int, float, float, object, int, int]


@dataclass(frozen=True)
class Phrase:
    """一条 8 小节乐句。"""
    events: List[Event]
    transpose: int = 0       # 推荐移调（半音，+12 = 高一个八度）
    register: str = ""       # 该乐句落在什么音区、为什么
    role: str = ""           # 这条乐句在曲式里干什么


@dataclass(frozen=True)
class Melody:
    """一条旋律：若干 8 小节乐句 + 32 小节曲式 + 和声骨架。"""
    id: str
    name: str                # 工作名（提案/待定）
    key: str
    scale: str
    harmony: Tuple[str, ...] # 每小节一个级数（与伴奏用同一串，供 check_melody 校验）
    phrases: Dict[str, Phrase]
    form: Tuple[str, ...]    # 32 小节 = 4 条乐句
    mood: str = ""
    note: str = ""           # 写作说明（进文档）

    def phrase(self, name: str) -> Phrase:
        return self.phrases[name]

    @property
    def bars(self) -> int:
        return 8 * len(self.form)


